export interface LevelInfo {
  level: number;
  title: string;
  icon: string;
  minXp: number;
  nextMinXp: number | null;
  nextTitle: string | null;
  progress: number; // درصد تا سطح بعد (۰ تا ۱۰۰)
  xpIntoLevel: number;
  xpNeeded: number;
}

export function levelFromXp(xp: number): LevelInfo {
  let current = USER_LEVELS[0];
  for (const l of USER_LEVELS) {
    if (xp >= l.minXp) current = l;
    else break;
  }
  const next = USER_LEVELS.find((l) => l.level === current.level + 1) ?? null;
  const xpIntoLevel = xp - current.minXp;
  const xpNeeded = next ? next.minXp - current.minXp : 0;
  return {
    level: current.level,
    title: current.title,
    icon: current.icon,
    minXp: current.minXp,
    nextMinXp: next?.minXp ?? null,
    nextTitle: next?.title ?? null,
    progress: next ? Math.min(100, Math.round((xpIntoLevel / xpNeeded) * 100)) : 100,
    xpIntoLevel,
    xpNeeded,
  };
}

